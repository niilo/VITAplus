#!/usr/bin/env python3
"""Convert recorded touch events into a replay script, and summarise them.

Usage: tools/android/touch_events.py convert <events> <script> [--speed N]
       tools/android/touch_events.py summarise <events> [--speed N]

<events> is the text `getevent -t` writes, one event per line:

    [    12.345678] 0003 0035 000001a0

That is a timestamp in seconds, then the event type, code and value in
hexadecimal. The type 0x0003 is EV_ABS, the code 0x0035 is
ABS_MT_POSITION_X, and the value is 0x1a0, so 416.

`convert` writes a shell script for the device. It sleeps for the gap between
one event group and the next, then sends the group with `sendevent`. The
timing happens on the device, so a replay is not slowed by the round trip of
one adb call per event.

`summarise` prints one line per touch, with the time it started, its position
and how long it was held. Read it to check a recording without replaying it.

--speed divides every gap. 2 makes a replay twice as fast, 0.5 twice as slow.
"""

import argparse
import re
import sys

# Event codes used by a touchscreen. Only these are replayed, so a recording
# that picked up an unrelated device does not send that device's events.
EV_SYN = 0x00
EV_KEY = 0x01
EV_ABS = 0x03

SYN_REPORT = 0x00
ABS_MT_SLOT = 0x2F
ABS_MT_TOUCH_MAJOR = 0x30
ABS_MT_POSITION_X = 0x35
ABS_MT_POSITION_Y = 0x36
ABS_MT_TRACKING_ID = 0x39
ABS_MT_PRESSURE = 0x3A

ABS_CODES = frozenset([ABS_MT_SLOT, ABS_MT_TOUCH_MAJOR, ABS_MT_POSITION_X,
                       ABS_MT_POSITION_Y, ABS_MT_TRACKING_ID, ABS_MT_PRESSURE])

# "[    12.345678] 0003 0035 000001a0". Some builds print the device path
# between the timestamp and the codes, so that part is optional.
LINE = re.compile(r"^\[\s*(\d+)\.(\d+)\]\s*(?:/\S+:\s*)?"
                  r"([0-9a-fA-F]+)\s+([0-9a-fA-F]+)\s+(-?[0-9a-fA-F]+)\s*$")

HEADER = """#!/system/bin/sh
# Replay of recorded touches, generated by tools/android/touch_events.py.
# Device node {node}. Run it with: adb shell sh <script>
D={node}
"""


def signed_32(value):
    """getevent prints a negative value as unsigned hex, so turn it back.

    A released finger is ABS_MT_TRACKING_ID -1, which getevent writes as
    ffffffff. Read as it stands that is 4294967295, and the release would never
    be seen.
    """
    return value - 0x100000000 if value >= 0x80000000 else value


def parse_events(text):
    """Return [(seconds, type, code, value)] for the touchscreen events.

    Values are kept as they were written, so a replay sends the same numbers
    the finger produced. Events of other types are dropped.
    """
    events = []
    for line in text.splitlines():
        if not line.strip():
            continue
        match = LINE.match(line)
        if not match:
            continue
        seconds = int(match.group(1)) + int(match.group(2)) / 1_000_000
        kind = int(match.group(3), 16)
        code = int(match.group(4), 16)
        value = signed_32(int(match.group(5), 16))
        if kind == EV_ABS and code in ABS_CODES:
            events.append((seconds, kind, code, value))
        elif kind == EV_SYN and code == SYN_REPORT:
            events.append((seconds, kind, code, value))
        elif kind == EV_KEY:
            events.append((seconds, kind, code, value))
    return events


def group_events(events):
    """Group [(seconds, ...)] into [(seconds, [events])], one group per timestamp."""
    groups = []
    for event in events:
        if groups and groups[-1][0] == event[0]:
            groups[-1][1].append(event[1:])
        else:
            groups.append((event[0], [event[1:]]))
    return groups


def touches(events):
    """Return [(start, end, x, y)] for each completed touch.

    A touch begins when ABS_MT_TRACKING_ID becomes not negative, and ends when
    it becomes negative. A touch that never ends is reported with end None.
    """
    found = []
    start = None
    x = y = 0
    for seconds, kind, code, value in events:
        if kind == EV_ABS and code == ABS_MT_POSITION_X:
            x = value
        elif kind == EV_ABS and code == ABS_MT_POSITION_Y:
            y = value
        elif kind == EV_ABS and code == ABS_MT_TRACKING_ID:
            if value >= 0:
                start, x, y = seconds, x, y
            elif start is not None:
                found.append((start, seconds, x, y))
                start = None
    if start is not None:
        found.append((start, None, x, y))
    return found


def write_script(groups, path, node, source):
    """Write a device-side shell script that replays the groups.

    The gaps are the ones the groups carry, so the caller scales them first and
    the script needs no speed argument on the device.
    """
    lines = [HEADER.format(node=node), "# Source: {}\n".format(source)]
    previous = groups[0][0] if groups else 0
    for seconds, group in groups:
        gap = seconds - previous
        if gap > 0:
            lines.append("sleep {}\n".format(format_time(gap)))
        for kind, code, value in group:
            lines.append("sendevent $D {:d} {:d} {:d}\n".format(kind, code, value))
        previous = seconds
    with open(path, "w") as handle:
        handle.write("".join(lines))


def format_time(seconds):
    """A plain decimal, with enough digits for a tenth of a millisecond."""
    return "%.4f" % seconds


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)

    convert = sub.add_parser("convert")
    convert.add_argument("events")
    convert.add_argument("script")
    convert.add_argument("--node", default="/dev/input/event4")
    convert.add_argument("--speed", type=float, default=1.0)

    summary = sub.add_parser("summarise")
    summary.add_argument("events")
    summary.add_argument("--speed", type=float, default=1.0)

    args = parser.parse_args()
    if args.speed <= 0:
        parser.error("--speed must be above zero")

    with open(args.events) as handle:
        events = parse_events(handle.read())
    if not events:
        print("no touchscreen events in " + args.events, file=sys.stderr)
        return 1

    if args.command == "convert":
        groups = group_events(events)
        # Apply the speed by scaling the gaps, so the script itself holds the
        # already-scaled sleeps and needs no speed argument on the device.
        if args.speed != 1.0:
            first = groups[0][0]
            groups = [(first + (seconds - first) / args.speed, group) for seconds, group in groups]
        write_script(groups, args.script, args.node, args.events)
        print("{}: {} events, {} groups, {:.1f} s".format(
            args.script, len(events), len(groups), groups[-1][0] - groups[0][0]))
        return 0

    first = events[0][0]
    found = touches(events)
    print("{} touches over {:.1f} s".format(len(found), events[-1][0] - first))
    for start, end, x, y in found:
        held = "open" if end is None else "{:.0f} ms".format((end - start) * 1000)
        print("  {:7.2f} s  x={:5d} y={:5d}  held {}".format(start - first, x, y, held))
    return 0


if __name__ == "__main__":
    sys.exit(main())
